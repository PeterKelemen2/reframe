def _read_data(name: str) -> Any:
    data = importlib.resources.files("reframe") / "definitions" / "data" / name
    return json.loads(gzip.decompress(data.read_bytes()))


@dataclass(frozen=True, slots=True)
class _Core:
    """Codes, canonical forms and English names: what every tag operation needs."""

    valid: frozenset[str]
    grandfathered: frozenset[str]
    suppress_script: dict[str, str]
    macrolanguage: dict[str, str]
    language_aliases: dict[str, str]
    territory_aliases: dict[str, str]
    cldr_macrolanguage: dict[str, str]
    alpha3_t: dict[str, str]
    alpha3_b: dict[str, str]
    canonical: dict[str, str | None]
    english: dict[str, dict[str, str]]
    english_separator: str
    english_pattern: str
    native: dict[str, str]


@functools.cache
def _core() -> _Core:
    data = _read_data(_CORE_FILE)
    registry = data["registry"]
    kinds = ("language", "extlang", "script", "region", "variant")
    english = data["english"]
    return _Core(
        valid=frozenset(s for kind in kinds for s in registry[kind]["subtags"]),
        grandfathered=frozenset(registry["grandfathered"]),
        suppress_script=registry["language"]["Suppress-Script"],
        macrolanguage=registry["language"]["Macrolanguage"],
        language_aliases=data["aliases"]["language"],
        territory_aliases=data["aliases"]["territory"],
        cldr_macrolanguage=data["aliases"]["macrolanguage"],
        alpha3_t=data["alpha3"]["T"],
        alpha3_b=data["alpha3"]["B"],
        canonical=data["canonical"],
        english={kind: english[kind] for kind in ("language", "script", "territory")},
        english_separator=english["separator"],
        english_pattern=english["pattern"],
        native=data["native"],
    )


@dataclass(frozen=True, slots=True)
class _LocaleNames:
    """Names in each locale and CLDR's matching data, for the native name of any tag."""

    names: dict[str, dict[str, dict[str, str]]]
    likely: dict[str, str]
    distance: dict[str, dict[str, int]]
    regions: dict[str, frozenset[str]]
    default_territory_distance: int
    separators: tuple[tuple[str, str], ...]


@functools.cache
def _locale_names() -> _LocaleNames:
    data = _read_data(_LOCALE_NAMES_FILE)
    return _LocaleNames(
        names={kind: data[kind] for kind in ("language", "script", "territory")},
        likely=data["likely"],
        distance=data["distance"],
        regions={name: frozenset(codes) for name, codes in data["regions"].items()},
        default_territory_distance=data["default_territory_distance"],
        separators=tuple((k, v) for k, v in data["separators"]),
    )


@functools.cache
def _search_tables() -> tuple[dict[str, str | None], ...]:
    """Normalised language names → canonical tag (``None``: the name's tag is not valid):
    English names first, then the names in every locale."""
    data = _read_data(_SEARCH_FILE)
    tables = []
    for locale in ("en", "und"):
        table: dict[str, str | None] = {}
        for tag, names in data[locale].items():
            table.update(dict.fromkeys(names, tag or None))
        tables.append(table)
    return tuple(tables)


class _TagError(ValueError):
    """Text that is not a BCP 47 tag."""


@dataclass(frozen=True, slots=True, eq=False)
class _Tag:
    """A parsed tag. Equal when the tag strings are equal."""

    language: str | None = None
    extlangs: tuple[str, ...] = ()
    script: str | None = None
    territory: str | None = None
    variants: tuple[str, ...] = ()
    extensions: tuple[str, ...] = ()
    private: str | None = None
    tag: str = field(init=False)

    def __post_init__(self) -> None:
        parts = [
            self.language or UNDETERMINED,
            *sorted(self.extlangs),
            *([self.script] if self.script else []),
            *([self.territory] if self.territory else []),
            *sorted(self.variants),
            *self.extensions,
            *([self.private] if self.private else []),
        ]
        object.__setattr__(self, "tag", "-".join(parts))

    def __eq__(self, other: object) -> bool:
        return isinstance(other, _Tag) and self.tag == other.tag

    def __hash__(self) -> int:
        return hash(self.tag)


_EXTLANG, _SCRIPT, _TERRITORY, _VARIANT, _EXTENSION = range(5)


def _parse_tag(tag: str) -> list[tuple[str, str]]:
    """The subtags of ``tag`` as ``(kind, value)``, with BCP 47 case; raises :class:`_TagError`."""
    if not tag.isascii():
        raise _TagError(tag)
    tag = tag.lower().replace("_", "-")
    if tag in _core().grandfathered:
        return [("grandfathered", tag)]
    subtags = tag.split("-")
    if any(not 1 <= len(s) <= 8 or not s.isalnum() for s in subtags):
        raise _TagError(tag)
    if subtags[0] == "x":
        if len(subtags) == 1:
            raise _TagError(tag)
        return [("language", tag)]
    if not 2 <= len(subtags[0]) <= 4:
        raise _TagError(tag)
    return [("language", subtags[0]), *_parse_subtags(subtags[1:], _EXTLANG)]


def _parse_subtags(subtags: list[str], expect: int) -> list[tuple[str, str]]:
    parsed: list[tuple[str, str]] = []
    i = 0
    while i < len(subtags):
        subtag = subtags[i]
        kind: int | None = None
        if len(subtag) == 1:
            return parsed + _parse_extension(subtags[i:])
        if len(subtag) == 2:
            kind = _TERRITORY if subtag.isalpha() else None
        elif len(subtag) == 3:
            if subtag.isalpha():
                if expect > _EXTLANG:
                    raise _TagError(subtag)
                # Up to three extlangs; any three-character subtag counts, digits too.
                end = i
                while end < len(subtags) and len(subtags[end]) == 3 and end - i < 3:
                    parsed.append(("extlang", subtags[end]))
                    end += 1
                i, expect = end, _SCRIPT
                continue
            kind = _TERRITORY if subtag.isdigit() else None
        elif len(subtag) == 4:
            if subtag.isalpha():
                kind = _SCRIPT
            elif subtag[0].isdigit():
                kind = _VARIANT
        else:
            kind = _VARIANT
        if kind is None or kind < expect:
            raise _TagError(subtag)
        expect = kind + 1 if kind in (_SCRIPT, _TERRITORY) else kind
        if kind == _SCRIPT:
            parsed.append(("script", subtag.title()))
        elif kind == _TERRITORY:
            parsed.append(("territory", subtag.upper()))
        else:
            parsed.append(("variant", subtag))
        i += 1
    return parsed


def _parse_extension(subtags: list[str]) -> list[tuple[str, str]]:
    if len(subtags) == 1:
        raise _TagError(subtags[0])
    if subtags[0] == "x":
        return [("private", "-".join(subtags))]
    end = 1
    while end < len(subtags) and len(subtags[end]) != 1:
        end += 1
    if end == 1:
        raise _TagError(subtags[0])
    return [("extension", "-".join(subtags[:end])), *_parse_subtags(subtags[end:], _EXTENSION)]


def _fields(tag: _Tag) -> dict[str, Any]:
    """The set attributes of ``tag``."""
    values = {
        "language": tag.language,
        "extlangs": list(tag.extlangs),
        "script": tag.script,
        "territory": tag.territory,
        "variants": list(tag.variants),
        "extensions": list(tag.extensions),
        "private": tag.private,
    }
    return {key: value for key, value in values.items() if value}


def _make(data: dict[str, Any]) -> _Tag:
    return _Tag(
        language=data.get("language"),
        extlangs=tuple(data.get("extlangs", ())),
        script=data.get("script"),
        territory=data.get("territory"),
        variants=tuple(data.get("variants", ())),
        extensions=tuple(data.get("extensions", ())),
        private=data.get("private"),
    )


@functools.lru_cache(maxsize=8192)
def _get(tag: str, normalize: bool) -> _Tag:
    """Parse ``tag``; ``normalize`` replaces deprecated and overlong codes (``iw`` → ``he``,
    ``sgn-US`` → ``ase``) as CLDR's alias tables say. Raises :class:`_TagError`."""
    core = _core()
    lower = tag.lower().replace("_", "-")
    if normalize and lower in core.language_aliases:
        tag = core.language_aliases[lower]
    data: dict[str, Any] = {}
    for kind, value in _parse_tag(tag):
        if kind == "extlang" and normalize and "language" in data:
            replacement = core.language_aliases.get(f"{data['language']}-{value}")
            if replacement is not None:
                data.update(_fields(_get(replacement, True)))
            else:
                data.setdefault("extlangs", []).append(value)
        elif kind in ("extlang", "variant", "extension"):
            data.setdefault(f"{kind}s", []).append(value)
        elif kind == "language":
            if value == UNDETERMINED:
                continue
            replacement = core.language_aliases.get(value) if normalize else None
            if replacement is not None:
                data.update(_fields(_get(replacement, True)))
            else:
                data["language"] = value
        elif kind == "territory":
            data["territory"] = (
                core.territory_aliases.get(value.lower(), value) if normalize else value
            )
        elif kind == "grandfathered":
            data["language"] = value
        else:
            data[kind] = value
    return _make(data)


def _is_valid(tag: _Tag) -> bool:
    """Every subtag is in the IANA registry, at most one extlang, no subtag twice."""
    if len(tag.extlangs) > 1:
        return False
    subtags = [s for s in (tag.language, tag.script, tag.territory, *tag.variants) if s]
    valid = _core().valid
    if any(not s.startswith("x-") and s not in valid for s in subtags):
        return False
    checked = subtags + [extension[:2] for extension in tag.extensions]
    return len(set(checked)) == len(checked)


def _simplify_script(tag: _Tag) -> _Tag:
    """Without the script when it is the language's ``Suppress-Script`` (``en-Latn`` → ``en``)."""
    if tag.language and tag.script and _core().suppress_script.get(tag.language) == tag.script:
        return replace(tag, script=None)
    return tag


def _prefer_macrolanguage(tag: _Tag) -> _Tag:
    """CLDR's dominant-language rule: ``cmn`` → ``zh``, ``arb`` → ``ar``."""
    macro = _core().cldr_macrolanguage.get(tag.language or UNDETERMINED)
    return tag if macro is None else replace(tag, language=macro)


def _alpha3(language: str | None, variant: str) -> str:
    """ISO 639-2 code (/B or /T) of a language subtag; raises ``LookupError`` if unknown."""
    if language is None:
        return UNDETERMINED
    if len(language) == 3:
        return language
    core = _core()
    if variant == "B" and language in core.alpha3_b:
        return core.alpha3_b[language]
    if language in core.alpha3_t:
        return core.alpha3_t[language]
    raise LookupError(f"{language!r} has no ISO 639-2 code")


@functools.cache
def _iso639_2_codes() -> frozenset[str]:
    """Every ISO 639-2 code, /B and /T (``ger`` and ``deu``), and the collective codes."""
    b_codes = {_alpha3(_parse(code).language, "B") for code in _canonical_639_2()}
    return _ISO639_2T | _ISO639_2_COLLECTIVE | b_codes


def _is_iso639_2(code: str) -> bool:
    return code in _iso639_2_codes() or "qaa" <= code <= "qtz"  # qaa-qtz: local use


@functools.cache
def _canonical_639_2() -> tuple[str, ...]:
    """The canonical tag of every ISO 639-2 language and special code, sorted, no duplicates."""
    tags = {_normalize_code(code) for code in _ISO639_2T}
    return tuple(sorted(tag for tag in tags if tag is not None))


@functools.lru_cache(maxsize=4096)
def _parse(tag: str) -> _Tag:
    """A canonical tag, parsed (no second normalisation: ``tl`` stays ``tl``)."""
    return _get(tag, False)


def _fold(text: str) -> str:
    """Case- and accent-insensitive form for name matching (``Français`` → ``francais``)."""
    decomposed = unicodedata.normalize("NFKD", text.casefold())
    return "".join(ch for ch in decomposed if not unicodedata.combining(ch)).strip()


def _code_language(text: str) -> _Tag | None:
    """Parse code-shaped input (BCP 47 / ISO 639) with the overrides, or ``None``."""
    text = text.strip().replace("_", "-")
    if not is_language_tag(text):
        return None
    primary = text.split("-", 1)[0].lower()
    try:
        if primary in OVERRIDES:
            return replace(_get(text, False), language=OVERRIDES[primary])
        return _get(text, True)
    except _TagError:
        return None


@functools.lru_cache(maxsize=4096)
def _normalize_code(text: str) -> str | None:
    """Canonical tag for code-shaped input only (no name lookup), or ``None``."""
    raw = text.strip().replace("_", "-")
    code = raw.lower()
    # The shape is checked before lowering: the Kelvin sign lowers to an ASCII "k".
    if "-" not in code and code not in OVERRIDES and LANGUAGE_TAG_PATTERN.fullmatch(raw):
        core = _core()
        if code in core.canonical:
            return core.canonical[code]
        # A primary subtag has 2 to 4 letters: "akuapem" is a variant, not a language.
        return code if len(code) <= 4 and code in core.valid else None
    lang = _code_language(text)
    if lang is None or not _is_valid(lang):
        return None
    return lang.tag if LANGUAGE_TAG_PATTERN.fullmatch(lang.tag) else None


def _looks_like_name(text: str) -> bool:
    """Starts with a letter, at most 100 characters, no digit, ``_`` or control character."""
    text = unicodedata.normalize("NFKC", text)
    return (
        len(text) <= _MAX_NAME_LENGTH
        and text[:1].isalpha()
        and not any(
            ch.isdigit() or ch == "_" or unicodedata.category(ch).startswith("C") for ch in text
        )
    )


def _search_key(name: str) -> str:
    """The form the name tables are keyed by: ``Chinese (Traditional)`` → ``chinese
    traditional``."""
    name = name.casefold().replace("\u2019", "'").replace("-", " ")
    return name.replace("(", "").replace(")", "").replace(",", "").strip()


def _find_name(table: dict[str, str | None], key: str) -> tuple[bool, str | None]:
    """Look ``key`` up, else its longest prefix of at least 4 characters (``Hakka Chinese``
    finds ``Hakka``). ``(found, tag)``."""
    for end in (len(key), *range(len(key) - 1, 3, -1)):
        if key[:end] in table:
            return True, table[key[:end]]
    return False, None


@functools.lru_cache(maxsize=1024)
def _normalize_name(text: str) -> str | None:
    """Canonical tag for a language name (English or native, any case/accents), or ``None``.

    Only text that looks like a name is looked up (:func:`_looks_like_name`): the prefix match
    would turn ``-en`` into ``enc``.
    """
    if not _looks_like_name(text):
        return None
    known = _name_index().get(_fold(text))
    if known is not None:
        return known
    key = _search_key(text)
    for table in _search_tables():
        found, tag = _find_name(table, key)
        if found:
            return tag
    return None


def normalize(value: str | None) -> str | None:
    """The canonical BCP 47 tag for a code, tag or language name, or ``None`` if invalid.

    Idempotent: ``normalize(normalize(x)) == normalize(x)``.
    """
    if value is None or not value.strip():
        return None
    return _normalize_code(value) or _normalize_name(value.strip())


def validate(value: str | None) -> str | None:
    """``None`` if :func:`normalize` accepts ``value``, else the reason in plain words."""
    if value is None or not value.strip():
        return "No language given: enter a language name or code, for example hu or pt-BR."
    if normalize(value) is not None:
        return None
    text = value.strip().replace("_", "-")
    if text[:2].lower() == "x-":
        return f"{value!r}: private-use tags (x-...) are not supported."
    if "-" not in text or not LANGUAGE_TAG_PATTERN.fullmatch(text):
        return f"{value!r} is not a known language name or code."
    lang = _code_language(text)
    if lang is None:
        return f"{value!r} is not a valid language tag (BCP 47)."
    checks = [
        ("language code", lang.language, _Tag(language=lang.language)),
        ("script", lang.script, _Tag(script=lang.script)),
        ("region", lang.territory, _Tag(territory=lang.territory)),
        *(("variant", v, _Tag(variants=(v,))) for v in lang.variants),
    ]
    for kind, subtag, single in checks:
        if subtag is not None and not _is_valid(single):
            return f"{value!r}: {subtag!r} is not a known {kind}."
    return f"{value!r} is not a valid language tag (BCP 47)."


def _language_or_und(value: str | None) -> _Tag:
    tag = normalize(value)
    return _parse(tag if tag is not None else UNDETERMINED)


def base_language(value: str | None) -> str:
    """The primary language subtag of the canonical tag. ``und`` for ``und`` and for invalid
    input."""
    return _language_or_und(value).language or UNDETERMINED


def _iso639_2(value: str | None, variant: str) -> str:
    language = _language_or_und(value).language
    if language is None:
        return UNDETERMINED
    for candidate in (language, _core().macrolanguage.get(language)):
        if candidate is None:
            continue
        try:
            code = _alpha3(_parse(candidate).language, variant)
        except LookupError:  # pragma: no cover - every valid 2-letter code has one
            continue
        if _is_iso639_2(code):
            return code
    return UNDETERMINED


def to_matroska_legacy(value: str | None) -> str:
    """ISO 639-2/B for the Matroska ``Language`` element. A language without a code of its own
    gets its macrolanguage's (``yue`` → ``chi``); ``und`` if unknown."""
    return _iso639_2(value, "B")


def to_mp4(value: str | None) -> str:
    """ISO 639-2/T for the MP4 ``mdhd`` language; ``und`` if unknown."""
    return _iso639_2(value, "T")


def to_matroska_ietf(value: str | None) -> str:
    """BCP 47 for the Matroska ``LanguageIETF`` element: the canonical tag, ``und`` if
    invalid."""
    return normalize(value) or UNDETERMINED


_PLACEHOLDERS: Final = {"language": UNDETERMINED, "script": "Zzzz", "territory": "ZZ"}
_UNKNOWN_SUBTAG: Final = "Unknown language subtag"


def _english_part(kind: str, code: str) -> str:
    names = _core().english[kind]
    if code in names:
        return names[code]
    return f"{names.get(_PLACEHOLDERS[kind], _UNKNOWN_SUBTAG)} [{code}]"


def _english_display(tag: _Tag) -> str:
    """``Language (script, region)`` in English; variants are not named."""
    core = _core()
    reduced = _simplify_script(tag)
    name = _english_part("language", reduced.language or UNDETERMINED)
    details = [
        _english_part(kind, code)
        for kind, code in (("script", reduced.script), ("territory", reduced.territory))
        if code is not None
    ]
    if not details:
        return name
    return core.english_pattern.format(name, core.english_separator.join(details))


def english_name(value: str | None) -> str:
    """English display name; ``Undetermined`` for ``und`` and for invalid input."""
    lang = _language_or_und(value)
    if lang.tag in _NAME_OVERRIDES:
        return _NAME_OVERRIDES[lang.tag]
    return _english_display(lang)


@functools.lru_cache(maxsize=4096)
def _autonym(tag: str) -> str:
    known = _core().native.get(tag)
    if known is not None:
        return known
    if "-" not in tag:
        # The table leaves out a language whose autonym is its English name.
        return _english_display(_parse(tag))
    return _autonym_from_locales(_parse(tag))


def native_name(value: str | None, *, capitalize: bool = False) -> str:
    """The language's name in itself (CLDR autonym), or the English name when CLDR has none
    (and for ``und``, ``mul``, ...).

    ``capitalize=True`` upper-cases only the first letter.
    """
    lang = _language_or_und(value)
    if lang.language is None or lang.language in SPECIAL_CODES:
        name = english_name(value)
    else:
        name = _autonym(lang.tag)
    return name[:1].upper() + name[1:] if capitalize else name


# The native name of a tag outside the tables: each part is named in the CLDR locale closest
# to the tag (CLDR's language matching), else in English.

_AUTONYM_MAX_DISTANCE: Final = 9
_MATCH_MAX_DISTANCE: Final = 25
_BROADER_KEYS: Final = (
    ("language", "script", "territory"),
    ("language", "territory"),
    ("language", "script"),
    ("language",),
    ("script",),
    (),
)


def _autonym_from_locales(tag: _Tag) -> str:
    lang = _prefer_macrolanguage(tag)
    reduced = _simplify_script(lang)
    locale = _get(lang.tag, True)
    name = _locale_name("language", reduced.language or UNDETERMINED, locale)
    details = [
        _locale_name(kind, code, locale)
        for kind, code in (("script", reduced.script), ("territory", reduced.territory))
        if code is not None
    ]
    if not details:
        return name
    return _display_pattern(locale).format(name, _display_separator(locale).join(details))


@functools.lru_cache(maxsize=4096)
def _names_of(kind: str, code: str) -> dict[str, str]:
    """``{locale: name}`` of a language, script or region code."""
    names = dict(_locale_names().names[kind].get(code, {}))
    english = _core().english[kind].get(code)
    if english is not None:
        names["en"] = english
    return names


def _locale_name(kind: str, code: str, locale: _Tag) -> str:
    name = _best_name(_names_of(kind, code), locale)
    if name is not None:
        return name
    unknown = _best_name(_names_of(kind, _PLACEHOLDERS[kind]), locale) or _UNKNOWN_SUBTAG
    return f"{unknown} [{code}]"


def _best_name(names: dict[str, str], locale: _Tag) -> str | None:
    matchable = set(_broader_tags(locale))
    candidates = [key for key in sorted(names) if key in matchable]
    target = _closest_match(locale.tag, tuple(candidates), _AUTONYM_MAX_DISTANCE)
    return names[target] if target in names else names.get("en")


def _only(tag: _Tag, keys: tuple[str, ...]) -> _Tag:
    return _Tag(
        language=tag.language if "language" in keys else None,
        script=tag.script if "script" in keys else None,
        territory=tag.territory if "territory" in keys else None,
    )


@functools.lru_cache(maxsize=4096)
def _broader_tags(tag: _Tag) -> tuple[str, ...]:
    """``tag``, then ever broader forms of it and of its macrolanguage form, down to ``und``."""
    tags = [tag.tag]
    for keys in _BROADER_KEYS:
        for start in (tag, _prefer_macrolanguage(tag)):
            broader = _only(start, keys).tag
            if broader not in tags:
                tags.append(broader)
    return tuple(tags)


@functools.lru_cache(maxsize=4096)
def _maximize(tag: _Tag) -> _Tag:
    """``tag`` with CLDR's likely script and region filled in (``pt`` → ``pt-Latn-BR``)."""
    likely = _locale_names().likely
    for broader in _broader_tags(tag):
        if broader in likely:
            base = _get(likely[broader], False)
            return _Tag(
                language=tag.language or base.language,
                extlangs=tag.extlangs or base.extlangs,
                script=tag.script or base.script,
                territory=tag.territory or base.territory,
                variants=tag.variants or base.variants,
                extensions=tag.extensions or base.extensions,
                private=tag.private or base.private,
            )
    raise LookupError(tag.tag)  # pragma: no cover - CLDR has a likely tag for und


def _triple(tag: _Tag) -> tuple[str | None, str | None, str | None]:
    if tag.language is None and tag.script is None and tag.territory is None:
        return UNDETERMINED, "Zzzz", "ZZ"
    full = _maximize(_prefer_macrolanguage(tag))
    return full.language, full.script, full.territory


def _distance(desired: _Tag, supported: _Tag) -> int:
    """CLDR's language matching distance (0 to about 135; lower is closer)."""
    if desired == supported:
        return 0
    return _triple_distance(_triple(desired), _triple(supported))


@functools.lru_cache(maxsize=4096)
def _triple_distance(
    desired: tuple[str | None, str | None, str | None],
    supported: tuple[str | None, str | None, str | None],
) -> int:
    if desired == supported:
        return 0
    data = _locale_names()
    table = data.distance
    d_language, d_script, d_territory = desired
    s_language, s_script, s_territory = supported
    distance = 0
    if d_language != s_language:
        default = table["*"]["*"]
        distance += table.get(str(d_language), {}).get(str(s_language), default)
    d_pair, s_pair = f"{d_language}_{d_script}", f"{s_language}_{s_script}"
    if d_script != s_script:
        distance += table.get(d_pair, {}).get(s_pair, table["*_*"]["*_*"])
    if d_territory != s_territory:
        distance += _territory_distance(d_language, d_pair, s_pair, d_territory, s_territory)
    return distance


def _territory_distance(
    language: str | None, d_pair: str, s_pair: str, desired: str | None, supported: str | None
) -> int:
    data = _locale_names()
    regions = data.regions

    def apart(group: str) -> bool:
        return (desired in regions[group]) != (supported in regions[group])

    if d_pair != s_pair:
        return data.default_territory_distance
    if language == "ar":
        return 5 if apart("maghreb") else data.default_territory_distance
    if language == "en":
        us = regions["us"]
        if (desired == "GB" and supported not in us) or (desired not in us and supported == "GB"):
            return 3
        return 5 if apart("us") else data.default_territory_distance
    if desired in regions["latin_america"] and supported == "419":
        return 1
    if language in ("es", "pt"):
        return 5 if apart("americas") else data.default_territory_distance
    if d_pair == "zh_Hant":
        return 5 if apart("cnsar") else data.default_territory_distance
    return data.default_territory_distance


@functools.lru_cache(maxsize=4096)
def _closest_match(desired: str, supported: tuple[str, ...], max_distance: int) -> str:
    """The first of ``supported`` closest to ``desired`` within ``max_distance``, else
    ``und``."""
    if desired in supported:
        return desired
    desired = _simplify_script(_get(desired, True)).tag
    if desired in supported:
        return desired
    wanted = _get(desired, True)
    best, best_distance = UNDETERMINED, max_distance + 1
    for candidate in supported:
        distance = _distance(wanted, _get(candidate, True))
        if distance < best_distance:
            best, best_distance = candidate, distance
    return best


def _display_separator(locale: _Tag) -> str:
    separators = dict(_locale_names().separators)
    keys = tuple(key for key, _ in _locale_names().separators)
    return separators[_closest_match(locale.tag, keys, _MATCH_MAX_DISTANCE)]


def _display_pattern(locale: _Tag) -> str:
    chinese = (_get("zh", True), _get("zh-Hant", True))
    if any(_distance(locale, zh) <= _MATCH_MAX_DISTANCE for zh in chinese):
        return "{0}\uff08{1}\uff09"
    return "{0} ({1})"


def short_code(value: str | None) -> str:
    """Upper-case ISO 639-2/B code for file names; ``UND`` for invalid input."""
    return to_matroska_legacy(value).upper()


def join_short_codes(values: Iterable[str | None], sep: str = "-") -> str:
    """:func:`short_code` of each value, duplicates removed, in order."""
    return sep.join(dict.fromkeys(short_code(v) for v in values))


def picker_label(value: str | None, *, container: Container = "mkv") -> str:
    """What the picker shows for a language: the English name, the ISO 639-2 code as the
    container writes it, and the BCP 47 tag.

    The ISO 639-2 code is /B for MKV and WebM and /T for MP4.
    """
    code = to_mp4(value) if container == "mp4" else to_matroska_legacy(value)
    return f"{english_name(value)} · {code} (ISO 639-2) · {to_matroska_ietf(value)} (BCP 47)"


@dataclass(frozen=True, slots=True)
class LanguageEntry:
    """One language for the picker (``GET /api/languages``)."""

    tag: str
    """Canonical BCP 47 tag (``hu``, ``pt-BR``): stored and written as ``LanguageIETF``."""
    iso639_1: str | None
    """ISO 639-1 code (``hu``), ``None`` if the language has none."""
    iso639_2b: str
    """ISO 639-2/B, written to the Matroska ``Language`` element (``hun``, ``ger``): the
    :func:`to_matroska_legacy` value, so the macrolanguage or ``und`` for a language without
    an ISO 639-2 code (``yue`` → ``chi``, ``sh`` → ``und``)."""
    iso639_2t: str
    """ISO 639-2/T, written to MP4 (``hun``, ``deu``): the :func:`to_mp4` value."""
    iso639_3: str
    """ISO 639-3 code of the base language (``hun``, ``deu``, ``hbs`` for ``sh``)."""
    english_name: str
    """``Hungarian``, ``Portuguese (Brazil)``."""
    native_name: str
    """CLDR autonym as CLDR writes it (``magyar``); the English name if CLDR has none."""
    variant: bool
    """A region or script variant of a base language (``pt-BR``)."""


@functools.lru_cache(maxsize=1024)
def _make_entry(tag: str) -> LanguageEntry:
    lang = _parse(tag)
    language = lang.language or UNDETERMINED
    return LanguageEntry(
        tag=tag,
        iso639_1=language if len(language) == 2 else None,
        iso639_2b=to_matroska_legacy(tag),
        iso639_2t=to_mp4(tag),
        iso639_3=_alpha3(_parse(language).language, "T"),
        english_name=english_name(tag),
        native_name=native_name(tag),
        variant=tag != language,
    )


def entry(value: str | None) -> LanguageEntry | None:
    """The :class:`LanguageEntry` for any valid code, tag or name (also outside
    :func:`language_list`, for example ``yue`` or ``de-AT``); ``None`` if invalid."""
    tag = normalize(value)
    return None if tag is None else _make_entry(tag)


def _sort_key(item: LanguageEntry) -> tuple[str, str]:
    return _fold(item.english_name), item.tag


@functools.cache
def language_list() -> tuple[LanguageEntry, ...]:
    """The picker languages, ordered by English name: the ISO 639-2 individual languages and
    macrolanguages, the special codes and :data:`COMMON_VARIANTS`. Collective codes and the
    languages that only ISO 639-3 has are left out (:func:`search` still finds them)."""
    variants = (tag for tag in (_normalize_code(v) for v in COMMON_VARIANTS) if tag is not None)
    tags = dict.fromkeys([*_canonical_639_2(), *variants])
    return tuple(sorted((_make_entry(tag) for tag in tags), key=_sort_key))


@functools.cache
def _name_index() -> dict[str, str]:
    """Folded English and native names of the list → tag (English names win)."""
    index: dict[str, str] = {}
    for item in language_list():
        index.setdefault(_fold(item.native_name), item.tag)
    for item in language_list():
        index[_fold(item.english_name)] = item.tag
    return index


# Match ranks, best first.
_RANK_TAG = 0  # the query is (or normalises to) the entry's tag: "de", "ger", "pt_br"
_RANK_CODE = 1  # the query is one of the entry's ISO codes: "por" for pt-BR
_RANK_ENGLISH = 2  # English name, exact
_RANK_NATIVE = 3  # native name, exact
_RANK_PREFIX = 4  # a name starts with the query
_RANK_WORD = 5  # a word of a name starts with the query: "brazil"
_RANK_SUBSTRING = 6  # a name contains the query
_RANK_FOUND = 7  # the name tables find the entry by a name in another language: "allemand"

_WORD_SPLIT: Final = re.compile(r"[\s()\-,/]+")


@dataclass(frozen=True, slots=True)
class _Searchable:
    """The folded strings that :func:`search` compares, computed once per entry."""

    tag: str
    codes: frozenset[str]
    english: str
    native: str
    words: tuple[str, ...]


@functools.lru_cache(maxsize=2048)
def _searchable(item: LanguageEntry) -> _Searchable:
    english, native = _fold(item.english_name), _fold(item.native_name)
    codes = (item.iso639_1, item.iso639_2b, item.iso639_2t, item.iso639_3)
    return _Searchable(
        tag=item.tag.casefold(),
        codes=frozenset(code for code in codes if code is not None),
        english=english,
        native=native,
        words=tuple(w for name in (english, native) for w in _WORD_SPLIT.split(name) if w),
    )


def _rank(item: LanguageEntry, folded: str, code_tag: str | None, name_tag: str | None) -> int:
    s = _searchable(item)
    if item.tag == code_tag or folded == s.tag:
        return _RANK_TAG
    if folded in s.codes:
        return _RANK_CODE
    if folded == s.english:
        return _RANK_ENGLISH
    if folded == s.native:
        return _RANK_NATIVE
    if s.english.startswith(folded) or s.native.startswith(folded):
        return _RANK_PREFIX
    if any(word.startswith(folded) for word in s.words):
        return _RANK_WORD
    if folded in s.english or folded in s.native:
        return _RANK_SUBSTRING
    if item.tag == name_tag:
        return _RANK_FOUND
    return -1


def search(
    query: str, *, favourites: Sequence[str] = (), limit: int | None = None
) -> list[LanguageEntry]:
    """Picker search, best match first.

    Matches the BCP 47 tag, ISO 639-1/2B/2T/3 codes, English and native names (case- and
    accent-insensitive). Order: exact tag or code, exact name, name prefix, word prefix,
    substring; ties by English name, base languages before variants. Matching ``favourites``
    (any form, ``Settings.languages.favourites``) come first. A valid tag, or a language name
    in any CLDR locale, that is not in :func:`language_list` adds an entry for it. An empty
    query returns the favourites, then the whole list.
    """
    fav_tags = list(dict.fromkeys(t for t in (normalize(f) for f in favourites) if t))
    fav_rank = {tag: i for i, tag in enumerate(fav_tags)}
    listed = language_list()
    listed_tags = {item.tag for item in listed}
    extra = [_make_entry(tag) for tag in fav_tags if tag not in listed_tags]
    text = query.strip()
    if not text:
        favs = [_make_entry(tag) for tag in fav_tags]
        result = favs + [item for item in listed if item.tag not in fav_rank]
        return result[:limit] if limit is not None else result

    folded = _fold(text)
    code_tag = _normalize_code(text)
    if code_tag is not None and code_tag not in listed_tags and code_tag not in fav_rank:
        extra.append(_make_entry(code_tag))
    scored = _score((*listed, *extra), folded, code_tag, None, fav_rank)
    if not scored and code_tag is None:
        # Nothing matched: try the name in any language ("Cantonese", "allemand"). Not done
        # when something matched, so "e" does not add the language "E".
        name_tag = _normalize_name(text)
        if name_tag is not None:
            listed_or_fav = name_tag in listed_tags or name_tag in fav_rank
            pool = (*listed, *extra) if listed_or_fav else (*listed, *extra, _make_entry(name_tag))
            scored = _score(pool, folded, None, name_tag, fav_rank)
    result = [item for _, item in sorted(scored, key=lambda pair: pair[0])]
    return result[:limit] if limit is not None else result


_ScoreKey = tuple[int, int, int, bool, str, str]


def _score(
    items: Iterable[LanguageEntry],
    folded: str,
    code_tag: str | None,
    name_tag: str | None,
    fav_rank: dict[str, int],
) -> list[tuple[_ScoreKey, LanguageEntry]]:
    scored: list[tuple[_ScoreKey, LanguageEntry]] = []
    for item in items:
        rank = _rank(item, folded, code_tag, name_tag)
        if rank < 0:
            continue
        fav = fav_rank.get(item.tag)
        key = (0 if fav is not None else 1, rank, fav or 0, item.variant, *_sort_key(item))
        scored.append((key, item))
    return scored


def _match_language(lang: _Tag) -> str:
    """Primary subtag with CLDR's dominant-language rule (``cmn`` → ``zh``)."""
    return _prefer_macrolanguage(lang).language or UNDETERMINED


def same_language(a: str | None, b: str | None) -> bool:
    """Same base language, with a macrolanguage and its dominant language equal (``cmn`` and
    ``zh``). Missing or invalid values count as ``und``, so ``und`` and ``None`` are equal."""
    return _match_language(_language_or_und(a)) == _match_language(_language_or_und(b))


def matches(rule: str | None, track: str | None) -> bool:
    """Whether a preset rule language matches a track language (one-way).

    The base languages must be the same (:func:`same_language`), and each script, region
    and variant subtag of the rule must also be on the track: rule ``pt`` matches tracks
    ``pt``, ``pt-BR``, ``por``; rule ``pt-BR`` matches only ``pt-BR`` (not ``pt``, not
    ``pt-PT``). A missing or invalid track language is ``und``; ``und`` matches only ``und``.
    An invalid rule matches nothing.
    """
    rule_tag = normalize(rule)
    if rule_tag is None:
        return False
    r, t = _parse(rule_tag), _language_or_und(track)
    if _match_language(r) != _match_language(t):
        return False
    if r.script is not None and r.script != t.script:
        return False
    if r.territory is not None and r.territory != t.territory:
        return False
    return set(r.variants) <= set(t.variants)
