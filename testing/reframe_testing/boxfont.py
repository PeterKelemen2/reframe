"""Build a tiny TrueType font with plain Python ("Reframe Box").

The ASS fixture attaches an open-licence font. :func:`reframe_testing.media.find_font` prefers a
real system font (DejaVu Sans, Liberation Sans or Noto Sans). Machines without one of them (for
example the Windows CI runners) get this font instead: every printable character is the same
filled box, so libass can render it and a burn-in is visible. The font is generated by this
project and is in the public domain (CC0), so it can be attached anywhere.
"""

from __future__ import annotations

import struct

FAMILY = "Reframe Box"
_UPM = 1000
_ADVANCE = 600
_FIRST_CHAR = 0x21
_LAST_CHAR = 0x17F  # ASCII, Latin-1 and Latin Extended-A (enough for the test texts)


def _rect(x0: int, y0: int, x1: int, y1: int) -> bytes:
    """A simple glyph with one clockwise rectangle contour (all points on the curve)."""
    points = [(x0, y0), (x0, y1), (x1, y1), (x1, y0)]
    header = struct.pack(">hhhhh", 1, x0, y0, x1, y1)
    data = header + struct.pack(">H", 3) + struct.pack(">H", 0) + bytes([0x01] * 4)
    prev_x = prev_y = 0
    xs = b""
    ys = b""
    for x, y in points:
        xs += struct.pack(">h", x - prev_x)
        ys += struct.pack(">h", y - prev_y)
        prev_x, prev_y = x, y
    return data + xs + ys


def _checksum(data: bytes) -> int:
    data += b"\0" * (-len(data) % 4)
    words: tuple[int, ...] = struct.unpack(f">{len(data) // 4}I", data)
    return sum(words) & 0xFFFFFFFF


def _name_table(family: str) -> bytes:
    names = {
        0: "Generated by reframe_testing.boxfont. Public domain (CC0).",
        1: family,
        2: "Regular",
        3: f"{family} Regular 1.000",
        4: f"{family} Regular",
        5: "Version 1.000",
        6: family.replace(" ", "") + "-Regular",
    }
    records = b""
    strings = b""
    for name_id, text in names.items():
        raw = text.encode("utf-16-be")
        records += struct.pack(">HHHHHH", 3, 1, 0x0409, name_id, len(raw), len(strings))
        strings += raw
    return struct.pack(">HHH", 0, len(names), 6 + len(records)) + records + strings


def _cmap_table() -> bytes:
    # Format 4: [0x20] -> glyph 1 (space), [0x21..0x17F] -> glyph 2 (box), [0xFFFF] end.
    seg_count = 3
    ends = [0x20, _LAST_CHAR, 0xFFFF]
    starts = [0x20, _FIRST_CHAR, 0xFFFF]
    deltas = [(1 - 0x20) & 0xFFFF, 0, 1]
    range_offsets = [0, 2 * (seg_count - 1), 0]  # segment 1 points at glyph_ids[0]
    glyph_ids = [2] * (_LAST_CHAR - _FIRST_CHAR + 1)
    body = (
        struct.pack(f">{seg_count}H", *ends)
        + struct.pack(">H", 0)
        + struct.pack(f">{seg_count}H", *starts)
        + struct.pack(f">{seg_count}H", *deltas)
        + struct.pack(f">{seg_count}H", *range_offsets)
        + struct.pack(f">{len(glyph_ids)}H", *glyph_ids)
    )
    search_range, entry_selector = 4, 1
    sub = (
        struct.pack(
            ">HHHHHHH",
            4,
            14 + len(body),
            0,
            seg_count * 2,
            search_range,
            entry_selector,
            seg_count * 2 - search_range,
        )
        + body
    )
    return struct.pack(">HHHHI", 0, 1, 3, 1, 12) + sub


def build_font(family: str = FAMILY) -> bytes:
    """Return the bytes of a valid TrueType font named ``family``."""
    glyphs = [
        _rect(50, 0, 550, 700),  # .notdef
        b"",  # space
        _rect(60, 0, 540, 700),  # box
    ]
    glyf = b""
    offsets = [0]
    for g in glyphs:
        glyf += g + b"\0" * (-len(g) % 4)
        offsets.append(len(glyf))
    loca = struct.pack(f">{len(offsets)}I", *offsets)
    hmtx = struct.pack(">HhHhHh", _ADVANCE, 50, _ADVANCE, 0, _ADVANCE, 60)
    head = struct.pack(
        ">IIIIHHqqhhhhHHhhh",
        0x00010000,
        0x00010000,
        0,  # checkSumAdjustment, set below
        0x5F0F3CF5,
        0x000B,
        _UPM,
        0,
        0,
        50,
        0,
        550,
        700,
        0,
        8,
        2,
        1,  # long loca offsets
        0,
    )
    hhea = struct.pack(
        ">IhhhHhhhhhhhhhhhH",
        0x00010000,
        800,
        -200,
        0,
        _ADVANCE,
        50,
        50,
        550,
        1,
        0,
        0,
        0,
        0,
        0,
        0,
        0,
        len(glyphs),
    )
    maxp = struct.pack(
        ">IHHHHHHHHHHHHHH", 0x00010000, len(glyphs), 4, 1, 0, 0, 2, 0, 0, 0, 0, 0, 0, 0, 0
    )
    os2 = struct.pack(
        ">HhHHHhhhhhhhhhhh10sIIII4sHHHhhhHHIIhhHHH",
        4,
        _ADVANCE,
        400,
        5,
        0,  # fsType 0: installable embedding
        650,
        600,
        0,
        75,
        650,
        600,
        0,
        350,
        50,
        300,
        0,
        bytes(10),
        1 | 2,  # Basic Latin, Latin-1 Supplement
        0,
        0,
        0,
        b"RFRM",
        0x40,  # REGULAR
        0x20,
        _LAST_CHAR,
        800,
        -200,
        0,
        800,
        200,
        1,  # Latin 1 code page
        0,
        500,
        700,
        0,
        0x20,
        1,
    )
    post = struct.pack(">IIhhIIIII", 0x00030000, 0, -100, 50, 0, 0, 0, 0, 0)
    tables = {
        b"OS/2": os2,
        b"cmap": _cmap_table(),
        b"glyf": glyf,
        b"head": head,
        b"hhea": hhea,
        b"hmtx": hmtx,
        b"loca": loca,
        b"maxp": maxp,
        b"name": _name_table(family),
        b"post": post,
    }
    num = len(tables)
    directory = struct.pack(">IHHHH", 0x00010000, num, 128, 3, num * 16 - 128)
    offset = 12 + 16 * num
    records = b""
    body = b""
    head_offset = 0
    for tag in sorted(tables):
        data = tables[tag]
        if tag == b"head":
            head_offset = offset + len(body)
        records += struct.pack(">4sIII", tag, _checksum(data), offset + len(body), len(data))
        body += data + b"\0" * (-len(data) % 4)
    font = bytearray(directory + records + body)
    adjustment = (0xB1B0AFBA - _checksum(bytes(font))) & 0xFFFFFFFF
    font[head_offset + 8 : head_offset + 12] = struct.pack(">I", adjustment)
    return bytes(font)
